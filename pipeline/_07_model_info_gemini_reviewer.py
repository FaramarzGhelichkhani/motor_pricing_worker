from google import genai
import json
from core.config import GEMINI_API_KEY_RESERVE, MODEL_NAME
from google.genai import types


client = genai.Client(api_key=GEMINI_API_KEY_RESERVE)

def generate_motorcycle_review(brand: str, model_name: str, specs: dict, raw_description: str) -> dict:
    """
    دیتا را به جمنای می‌دهد تا با ترکیب اطلاعات خام و دانش جهانی خود، 
    یک نقد حرفه‌ای شامل هویت، مشخصات، مخاطب هدف، مزایا، معایب و امتیازات تولید کند.
    """
    
    specs_str = json.dumps(specs, ensure_ascii=False) if specs else "مشخصاتی یافت نشد."
    desc_str = raw_description if raw_description else "توضیحاتی یافت نشد."
    
    prompt = f"""
            تو یک ژورنالیست، منتقد ارشد و کارشناس فنی کهنه‌کار موتور سیکلت هستی. 
            من نام و مشخصات خام یک موتور سیکلت را به تو می‌دهم. وظیفه تو این است که این داده‌های خام را با دانش جامع خودت، تاریخچه برند، مهندسی پلتفرم و عملکرد واقعی ترکیب کنی.

            قانون صفر (تثبیت هویت): تو فقط و فقط در حال بررسی موتورِ {brand} {model_name} هستی. تحت هیچ شرایطی، نام موتور دیگری را به عنوان موضوع اصلی در خروجی ننویس. اگر در توضیحات خام، نام مدل‌های دیگری برای مقایسه آمده بود، تمرکزت را از روی مدل اصلی از دست نده.

            اطلاعات موتور:
            - برند: {brand}
            - مدل: {model_name}
            - مشخصات فنی کراول شده: {specs_str}
            - توضیحات خام منبع: {desc_str}

            دستورالعمل‌های طلایی برای لحن و نگارش (بسیار مهم):
            ۱. تطابق دقیق با کلاس و رسالت: قبل از نوشتن، بر اساس مشخصات ارائه‌شده، کلاس موتور را تحلیل کن (اقتصادی شهری، تورینگ، ادونچر، اسپرت و...). لحن تو باید آینه تمام‌نمای رسالت همان موتور باشد. برای یک موتور اقتصادی و روزمره، مطلقاً از واژگان حماسی و اغراق‌آمیز (مثل درنده، هیولا، وحشی) استفاده نکن و روی مفاهیمی چون کارایی، دوام و هزینه‌ها تمرکز کن.
            ۲. واقع‌بینی مهندسی: مشخصات موتور را همان‌طور که هست بپذیر. یک موتور با توان خروجی پایین را به یک غول جاده‌ای تبدیل نکن. نقاط ضعف و قوت را کاملاً منطقی و متناسب با قیمت و کلاس آن بررسی کن.
            ۳. ادبیات تخصصی و غیررباتی: استفاده از عبارات کلیشه‌ای (مثل «این موتور تلفیقی از...»، «در دنیای پر رقابت امروز...»، «بدون شک...») مطلقاً ممنوع است. متن باید مستقیم، کوبنده و با اتوریته یک کارشناس خبره نوشته شود.
            ۴. ترجمه اعداد به تجربه سواری: مشخصات فنی را به صورت خام روخوانی نکن. اعداد مربوط به توان، گشتاور و وزن را تحلیل کن و توضیح بده که این نسبت‌ها، در عمل چه حسی به راکب می‌دهند (مثلاً تاثیر نسبت قدرت به وزن در مانورهای شهری یا پایداری در جاده).

            دستورالعمل‌های ساختار خروجی:
            ۵. برای هر فیلد متنی (identity, technical, target_audience) نهایتاً ۲ الی ۳ جمله غنی، پر از اطلاعات مفید و بدون حاشیه‌روی بنویس.
            ۶. مزایا و معایب (Pros & Cons): دقیقاً ۳ الی ۵ مورد استخراج کن. هر مورد باید یک جمله کوتاه، دقیق و کاملاً فنی باشد که ارزش افزوده یا ضعف واقعی را نشان دهد.
            ۷. امتیازدهی (Ratings): بر اساس دانش جهانی خودت از مهندسی و جایگاه بازار، به ۶ شاخص زیر امتیازی بین ۱ تا ۱۰۰ بده. توجه: نمره بالاتر همیشه یعنی "بهتر بودن" (مثلاً نمره ۸۰ در شاخص نگهداری، یعنی موتور کم‌هزینه و بی‌دردسری است).
            ۸. خروجی صرفاً به زبان فارسی روان و تخصصی باشد.

            خروجی باید دقیقاً یک فایل JSON تمیز با ساختار زیر باشد:
            {{
                "identity": "توصیف ذات، زبان طراحی و جایگاه این موتور در بازار و تاریخچه برند. (مستقیم برو سر اصل مطلب. رسالت اصلی این موتور چیست؟)",
                "technical": "تحلیل تخصصی و واقع‌بینانه عملکرد انجین، شاسی، تعلیق یا ترمزها با استفاده از اعداد و ارقام و تطبیق آن با کلاس موتور.",
                "target_audience": "این موتور دقیقاً برای چه کاربری، چه سطحی از مهارت و چه نوع استفاده‌ای مهندسی شده است؟",
                "pros": ["مزیت اول", "مزیت دوم", "مزیت سوم"],
                "cons": ["عیب اول", "عیب دوم", "عیب سوم"],
                "ratings": {{
                    "engine_performance": 0.0,
                    "design": 0.0,
                    "reliability": 0.0,
                    "fun_factor": 0.0,
                    "value_for_money": 0.0,
                    "maintenance_costs": 0.0
                }}
            }}

            هیچ متن اضافه‌ای (حتی مارک‌داون‌های ```json) تولید نکن و فقط خود ساختار JSON را برگردان.
"""
    try:
        response = client.models.generate_content(
                model=MODEL_NAME,
                contents=prompt,
                config=types.GenerateContentConfig(
                    response_mime_type="application/json",
                    temperature=0.2, 
                ),
            )
        result = json.loads(response.text)
        return result
    except Exception as e:
        print(f"Error generating content for {brand} {model_name}: {e}")
        return None
    